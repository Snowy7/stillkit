// Generates crates/ui/src/icon_paths.rs from Lucide's SVGs (ISC, see LICENSE-lucide here).
//
//   bun crates/ui/icons/gen.mjs <lucide-static>/icons
//
// Every element becomes SVG path data (circles, rects, lines and polylines are converted), so
// the renderer needs one parser: `icons::path` turns it into Direct2D geometry once per icon.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun gen.mjs <lucide-static>/icons");

// The icons the kit names (crates/ui/src/icons.rs), Lucide file names.
const NAMES = `
play pause skip-back skip-forward music shuffle repeat
chevron-left chevron-right chevron-up chevron-down
plus minus x check ellipsis settings search pencil trash-2 copy refresh-cw pin maximize-2
layout-grid power rotate-cw log-out lock bell bell-off calendar clock timer globe keyboard monitor
volume volume-1 volume-2 volume-x wifi wifi-zero wifi-low wifi-high wifi-off ethernet-port
bluetooth sun moon sun-moon leaf gauge thermometer cpu
battery battery-low battery-medium battery-full battery-charging battery-warning plug zap
notebook-pen list-checks image rss
cloud cloud-sun cloud-moon cloud-rain cloud-snow cloud-lightning cloud-fog cloud-drizzle snowflake
wind droplet umbrella sunrise sunset
speaker headphones mic house user star heart info triangle-alert download upload external-link
sliders-horizontal layers folder file clipboard grip-vertical arrow-up arrow-down plane map-pin
eye cast radio-tower accessibility camera app-window message-square terminal circle-user-round
palette undo-2 redo-2 mouse-pointer-2 move wrench video sparkles box images activity rocket quote coins
grid-3x3 toggle-right panel-top
`.trim().split(/\s+/);

const num = (v) => Number.parseFloat(v);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const pts = (s) => s.trim().split(/[\s,]+/).map(num);

function element(name, a) {
  switch (name) {
    case "path": {
      // A path's leading `m` is absolute, but not once paths are joined: make it `M`, and keep
      // its implicit line-tos relative.
      const m = a.d.match(/^\s*m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*,?/);
      if (!m) return a.d;
      const rest = a.d.slice(m[0].length);
      return `M${m[1]} ${m[2]}${/^[a-zA-Z]/.test(rest) || !rest ? "" : "l"}${rest}`;
    }
    case "circle": {
      const [cx, cy, r] = [num(a.cx), num(a.cy), num(a.r)];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [num(a.cx), num(a.cy), num(a.rx), num(a.ry)];
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
    }
    case "rect": {
      const [x, y, w, h] = [num(a.x ?? 0), num(a.y ?? 0), num(a.width), num(a.height)];
      const r = Math.min(num(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return (
        `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}` +
        `a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}` +
        `v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
      );
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const p = pts(a.points);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return name === "polygon" ? `${d}Z` : d;
    }
    default:
      throw new Error(`unsupported <${name}>`);
  }
}

const rows = NAMES.map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), "utf8");
  const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  const parts = [...body.matchAll(/<(\w+)([^>]*)\/>/g)].map((m) => element(m[1], attrs(m[2])));
  return `    ("${name}", "${parts.join("")}"),`;
});

writeFileSync(
  join(import.meta.dir, "../src/icon_paths.rs"),
  `//! Generated by crates/ui/icons/gen.mjs from Lucide 0.460.0 (ISC licence,
//! crates/ui/icons/LICENSE-lucide). Do not edit: change the list there and run it again.
//! Each icon is SVG path data on Lucide's 24-unit grid, drawn with round caps and joins.

pub(crate) const PATHS: &[(&str, &str)] = &[
${rows.join("\n")}
];
`,
);
console.log(`${rows.length} icons`);
